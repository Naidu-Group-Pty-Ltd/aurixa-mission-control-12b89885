-- ─── six private package buckets ────────────────────────────────────────────
-- 200 MB: a release APK is ~30-60 MB; the ceiling is headroom, not a target.
-- No storage policy is created: only the service role reads or writes a
-- package, and a download is a one-time ticket Mission Control streams.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
SELECT b, b, false, 209715200,
       ARRAY['application/vnd.android.package-archive','application/octet-stream']
FROM unnest(ARRAY[
  'mobile-releases-command-centre',
  'mobile-releases-client',
  'mobile-releases-finance',
  'mobile-releases-solicitor',
  'mobile-releases-builder',
  'mobile-releases-accountant'
]) AS b
ON CONFLICT (id) DO UPDATE
  SET public = false,
      file_size_limit = EXCLUDED.file_size_limit,
      allowed_mime_types = EXCLUDED.allowed_mime_types;

-- ─── reserve the gateway host ───────────────────────────────────────────────
-- mobile.aurixasystems.com.au is the gateway. 20260914120000's reasoning
-- applies unchanged: a host Aurixa owns is not a clones row, so only
-- reserved_slugs stops a customer claiming it. Both halves: the default for a
-- fresh install, the union for the row that exists.
ALTER TABLE public.platform_hosting_config
  ALTER COLUMN reserved_slugs SET DEFAULT array[
    'www','api','admin','app','mail','ftp','staging','dev','test','prod',
    'auth','portal','dashboard','status','docs','blog','cdn','assets','static',
    'mission-control','aurixa','root','ns1','ns2',
    'builders','builder','network','connect','partners',
    'mobile','apps','install','update'
  ];

UPDATE public.platform_hosting_config
SET reserved_slugs = (
      SELECT array(
        SELECT DISTINCT s
        FROM unnest(reserved_slugs || array['mobile','apps','install','update']) AS s
        ORDER BY s
      )
    ),
    updated_at = now()
WHERE singleton = true
  AND NOT (reserved_slugs @> array['mobile','apps','install','update']);
