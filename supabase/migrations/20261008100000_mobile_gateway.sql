-- ===========================================================================
-- The native mobile gateway and the mobile release registry.
--
-- @asserts table:clone_mobile_gateways
-- @asserts table:mobile_access_grants
-- @asserts table:mobile_activation_tickets
-- @asserts table:mobile_releases
-- @asserts table:mobile_release_rollouts
-- @asserts table:mobile_download_tickets
-- @asserts table:mobile_install_reports
-- @asserts table:clone_mobile_release_subscriptions
-- @asserts check:platform_hosting_config.reserved_slugs=mobile
--
-- No Aurixa app is listed on any public marketplace (the owner, 8 Oct 2026).
-- Every install and every update is handed out by Mission Control, and every
-- clone is connected to it from birth. This migration is the storage half of
-- that decision; npc-property-dashbord mobile/plan.md (Draft 03) is the whole.
--
-- ## Who may open which app: grants, keys and tickets
--
-- A GRANT is one principal of one clone allowed into one portal's app. Its
-- public reference (`grant_ref`, `mga_…`) appears in every link; its secret
-- half is generated by the app at its first claim and stored here only as a
-- hash, binding the grant to that installation. A TICKET is the single-use
-- thing a link actually carries — a magic link lives 15 minutes, a
-- provisioned URL 48 hours — and only its hash is stored. The ticket travels in
-- the URL fragment, so no server log ever holds it, and a GET of the link
-- consumes nothing: only the app's POST to the claim endpoint does, in one
-- conditional UPDATE.
--
-- ## The clone's own connection: clone_mobile_gateways
--
-- One row per clone, written at birth by step 5h of provisionCloneBackend and
-- converged for clones born earlier by the SAME function from the
-- clone-secrets reconcile sweep — so there is no second path that "injects"
-- the machinery, and no orphan. The row holds the clone mobile credential
-- (`mmc_…`) as a prefix and a SHA-256, the project ref it was delivered to, and
-- the portals the clone is licensed for.
--
-- ## Packages: mobile_releases and six private buckets
--
-- A release is a row; its package is an object in that portal's private
-- bucket, at {environment}/{platform}/{version}+{build}/{sha256}/artifact.
-- Packages are never bytea in a table. Nothing here is public: an install is a
-- one-time download ticket that Mission Control streams, and the app verifies
-- the signed manifest, the SHA-256 and the signing certificate before
-- installing anything.
--
-- ## Subscriptions
--
-- clone_mobile_release_subscriptions is one row per (clone, portal), written
-- at birth for all six portals. `enabled` says whether the clone may receive
-- that portal's releases; a portal the clone is not licensed for keeps its row
-- and is disabled, so licensing a portal later is a flag, not a birth.
--
-- Every table is read by operators and written only by the service role (the
-- server functions that own it). The buckets have no storage policy at all:
-- only the service role touches a package.
-- ===========================================================================

-- ─── clone_mobile_gateways ──────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.clone_mobile_gateways (
  clone_id UUID PRIMARY KEY REFERENCES public.clones(id) ON DELETE CASCADE,
  gateway_id TEXT NOT NULL UNIQUE,
  credential_prefix TEXT NOT NULL,
  credential_hash TEXT NOT NULL UNIQUE,
  delivered_project_ref TEXT,
  delivered_env_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'suspended', 'revoked')),
  licensed_portals TEXT[] NOT NULL DEFAULT ARRAY['command-centre']::text[],
  -- Draft 02 §11: native activation follows a 14 × 24-hour trial from THIS
  -- row's birth, plus extensions an operator authorised. A clone born before
  -- this table existed gets no retrial: it is admitted through a recorded,
  -- attributed exception instead (no gate backfill, no recharge).
  trial_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  trial_extension_hours INTEGER NOT NULL DEFAULT 0 CHECK (trial_extension_hours >= 0),
  cohort_enabled BOOLEAN NOT NULL DEFAULT true,
  legacy_clone BOOLEAN NOT NULL DEFAULT false,
  exception_granted_at TIMESTAMPTZ,
  exception_granted_by UUID,
  exception_reason TEXT,
  last_seen_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT clone_mobile_gateways_exception_attributed CHECK (
    exception_granted_at IS NULL
    OR (exception_granted_by IS NOT NULL AND length(coalesce(exception_reason, '')) >= 10)
  ),
  CONSTRAINT clone_mobile_gateways_portals_known CHECK (
    licensed_portals <@ ARRAY['command-centre','client','finance','solicitor','builder','accountant']::text[]
  )
);
ALTER TABLE public.clone_mobile_gateways ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Operators read clone_mobile_gateways" ON public.clone_mobile_gateways;
CREATE POLICY "Operators read clone_mobile_gateways" ON public.clone_mobile_gateways
  FOR SELECT TO authenticated USING (public.is_operator(auth.uid()));

-- ─── mobile_access_grants ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.mobile_access_grants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  grant_ref TEXT NOT NULL UNIQUE,
  clone_id UUID NOT NULL REFERENCES public.clones(id) ON DELETE CASCADE,
  portal TEXT NOT NULL CHECK (
    portal IN ('command-centre','client','finance','solicitor','builder','accountant')
  ),
  principal_kind TEXT NOT NULL DEFAULT 'superadmin'
    CHECK (principal_kind IN ('superadmin','staff','partner','client')),
  -- The principal's id IN THE CLONE (custom_users.id for staff). Mission
  -- Control never reads the clone's users; it records the id provisioning
  -- itself seeded, or the one an operator typed.
  principal_ref TEXT NOT NULL,
  principal_email TEXT,
  status TEXT NOT NULL DEFAULT 'issuable'
    CHECK (status IN ('issuable','active','device_bound','revoked')),
  key_hash TEXT,
  device_install_id TEXT,
  device_thumbprint TEXT,
  bound_at TIMESTAMPTZ,
  last_claimed_at TIMESTAMPTZ,
  revoked_at TIMESTAMPTZ,
  revoked_reason TEXT,
  created_by UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT mobile_access_grants_bound_has_device CHECK (
    status <> 'device_bound' OR (device_install_id IS NOT NULL AND key_hash IS NOT NULL)
  ),
  CONSTRAINT mobile_access_grants_revoked_has_time CHECK (
    status <> 'revoked' OR revoked_at IS NOT NULL
  )
);
CREATE INDEX IF NOT EXISTS idx_mobile_access_grants_clone
  ON public.mobile_access_grants(clone_id, portal);
CREATE UNIQUE INDEX IF NOT EXISTS uq_mobile_access_grants_live_principal
  ON public.mobile_access_grants(clone_id, portal, principal_ref)
  WHERE status <> 'revoked';
ALTER TABLE public.mobile_access_grants ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Operators read mobile_access_grants" ON public.mobile_access_grants;
CREATE POLICY "Operators read mobile_access_grants" ON public.mobile_access_grants
  FOR SELECT TO authenticated USING (public.is_operator(auth.uid()));

