-- ─── mobile_releases ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.mobile_releases (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  portal TEXT NOT NULL CHECK (
    portal IN ('command-centre','client','finance','solicitor','builder','accountant')
  ),
  platform TEXT NOT NULL CHECK (platform IN ('android','ios')),
  environment TEXT NOT NULL DEFAULT 'production'
    CHECK (environment IN ('production','staging')),
  channel TEXT NOT NULL DEFAULT 'stable' CHECK (channel IN ('stable','beta','internal')),
  version TEXT NOT NULL,
  build_number INTEGER NOT NULL CHECK (build_number > 0),
  source_sha TEXT NOT NULL,
  content_sha256 TEXT CHECK (content_sha256 IS NULL OR content_sha256 ~ '^[0-9a-f]{64}$'),
  signing_cert_sha256 TEXT CHECK (signing_cert_sha256 IS NULL OR signing_cert_sha256 ~ '^[0-9a-f]{64}$'),
  size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes > 0),
  min_os TEXT,
  min_supported_build INTEGER CHECK (min_supported_build IS NULL OR min_supported_build > 0),
  critical BOOLEAN NOT NULL DEFAULT false,
  release_notes TEXT,
  storage_bucket TEXT,
  storage_path TEXT,
  -- iOS packages are never stored or served here: the app is an Apple
  -- Business Manager Custom App and Apple delivers it. The row still governs
  -- the version and the minimum-version gate.
  apple_custom_app_url TEXT,
  state TEXT NOT NULL DEFAULT 'candidate'
    CHECK (state IN ('candidate','approved','promoted','paused','withdrawn')),
  uploaded_at TIMESTAMPTZ,
  approved_by UUID,
  approved_at TIMESTAMPTZ,
  promoted_at TIMESTAMPTZ,
  withdrawn_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT mobile_releases_unique_build
    UNIQUE (portal, platform, environment, channel, build_number),
  CONSTRAINT mobile_releases_android_has_package CHECK (
    platform <> 'android' OR state = 'candidate' OR state = 'withdrawn'
    OR (content_sha256 IS NOT NULL AND signing_cert_sha256 IS NOT NULL AND storage_path IS NOT NULL)
  ),
  CONSTRAINT mobile_releases_approval_recorded CHECK (
    state NOT IN ('approved','promoted','paused') OR approved_at IS NOT NULL
  )
);
ALTER TABLE public.mobile_releases ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Operators read mobile_releases" ON public.mobile_releases;
CREATE POLICY "Operators read mobile_releases" ON public.mobile_releases
  FOR SELECT TO authenticated USING (public.is_operator(auth.uid()));

